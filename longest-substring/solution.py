def longest_substring_bruteforce(s: str) -> int:
    """Return length of longest substring without repeating characters using O(n^2) check."""
    n = len(s)
    best = 0
    for i in range(n):
        seen = set()
        for j in range(i, n):
            if s[j] in seen:
                break
            seen.add(s[j])
            best = max(best, j - i + 1)
    return best

def longest_substring_window(s: str) -> int:
    """Return length of longest substring without repeating characters using sliding window."""
    last = {}
    left = 0
    best = 0
    for right, ch in enumerate(s):
        if ch in last and last[ch] >= left:
            left = last[ch] + 1
        last[ch] = right
        best = max(best, right - left + 1)
    return best
